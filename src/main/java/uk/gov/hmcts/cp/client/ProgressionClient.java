package uk.gov.hmcts.cp.client;

import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.core.io.ByteArrayResource;
import org.springframework.http.MediaType;
import org.springframework.stereotype.Component;
import org.springframework.util.LinkedMultiValueMap;
import org.springframework.util.MultiValueMap;
import org.springframework.web.client.RestClient;
import org.springframework.web.client.RestClientException;
import org.springframework.web.client.RestClientResponseException;
import uk.gov.hmcts.cp.config.ClientProperties;

import java.util.List;
import java.util.UUID;

/**
 * Attaches the rendered notification PDF to the case's Case Material section (feature 005 FR-020,
 * contracts/progression-court-document.md) via {@code cpp-context-progression}'s own
 * {@code progression-command-api} REST tier - not raw internal JMS commands, which this service has no existing
 * precedent for sending. Two calls to the same URL, distinguished by {@code Content-Type}:
 * <ol>
 *   <li>{@code multipart/form-data} (= {@code progression.upload-court-document}): stores the PDF bytes into
 *       Progression's own File Store; Progression derives the file's internal {@code fileServiceId} itself - this
 *       service never allocates or sees one (confirmed, not an open mechanics question).</li>
 *   <li>{@code application/vnd.progression.add-court-document+json} (= {@code progression.add-court-document}):
 *       attaches the stored file to the case under {@code documentTypeId} {@value #DOCUMENT_TYPE_ID}
 *       ("Electronic Notifications").</li>
 * </ol>
 * {@code materialId} is generated by this service ({@link java.util.UUID#randomUUID()}), not allocated by
 * Progression. The exact multipart field name below ({@code file}) is this feature's own assumption, not yet
 * confirmed against a real Progression sandbox (plan.md D14) - flagged, not silently guessed.
 */
@Slf4j
@Component
public class ProgressionClient {

    /* default */ static final String COURT_DOCUMENT_PATH = "/progression-command-api/command/api/rest/progression/courtdocument/{materialId}";
    /* default */ static final String DOCUMENT_TYPE_ID = "f471eb51-614c-4447-bd8d-28f9c2815c9e";
    /* default */ static final String DOCUMENT_NAME = "Electronic Notifications";
    private static final MediaType ADD_COURT_DOCUMENT_MEDIA_TYPE =
            MediaType.valueOf("application/vnd.progression.add-court-document+json");
    private static final String MULTIPART_FIELD_NAME = "file";

    private final RestClient restClient;
    private final String cjscppuid;

    public ProgressionClient(@Qualifier("progressionRestClientBuilder") final RestClient.Builder restClientBuilder,
                             final ClientProperties properties) {
        this.restClient = restClientBuilder.baseUrl(properties.getProgression().getBaseUrl()).build();
        this.cjscppuid = properties.getProgression().getCjscppuid();
    }

    /** Call 1: stores the PDF bytes; Progression derives its own {@code fileServiceId}. @throws ProgressionUnavailableException on failure */
    public void uploadFile(final UUID materialId, final byte[] pdfBytes) {
        final MultiValueMap<String, Object> parts = new LinkedMultiValueMap<>();
        parts.add(MULTIPART_FIELD_NAME, new ByteArrayResource(pdfBytes) {
            @Override
            public String getFilename() {
                return materialId + ".pdf";
            }
        });
        send(materialId, () -> restClient.post()
                .uri(COURT_DOCUMENT_PATH, materialId)
                .header("CJSCPPUID", cjscppuid)
                .contentType(MediaType.MULTIPART_FORM_DATA)
                .body(parts)
                .retrieve()
                .toBodilessEntity(), "upload-court-document");
    }

    /** Call 2: attaches the stored file to the case. @throws ProgressionUnavailableException on failure */
    public void addCourtDocument(final UUID materialId, final UUID prosecutionCaseId) {
        final AddCourtDocumentCommand command = new AddCourtDocumentCommand(new CourtDocument(UUID.randomUUID(),
                new DocumentCategory(new CaseDocument(prosecutionCaseId)), DOCUMENT_NAME,
                UUID.fromString(DOCUMENT_TYPE_ID), List.of(new MaterialRef(materialId)), MediaType.APPLICATION_PDF_VALUE,
                false));
        send(materialId, () -> restClient.post()
                .uri(COURT_DOCUMENT_PATH, materialId)
                .header("CJSCPPUID", cjscppuid)
                .contentType(ADD_COURT_DOCUMENT_MEDIA_TYPE)
                .body(command)
                .retrieve()
                .toBodilessEntity(), "add-court-document");
    }

    private void send(final UUID materialId, final Runnable call, final String commandName) {
        try {
            call.run();
        } catch (RestClientResponseException e) {
            log.warn("{} rejected for materialId {}: HTTP {} {}", commandName, materialId, e.getStatusCode().value(),
                    e.getStatusText());
            throw new ProgressionUnavailableException(commandName + " rejected for materialId " + materialId + ": "
                    + e.getClass().getSimpleName(), e);
        } catch (RestClientException e) {
            log.warn("{} failed for materialId {}: {} - {}", commandName, materialId, e.getClass().getSimpleName(),
                    e.getMessage());
            throw new ProgressionUnavailableException(commandName + " failed for materialId " + materialId + ": "
                    + e.getClass().getSimpleName(), e);
        }
    }

    /* default */ record AddCourtDocumentCommand(CourtDocument courtDocument) {
    }

    /* default */ record CourtDocument(UUID courtDocumentId, DocumentCategory documentCategory, String name,
                                       UUID documentTypeId, List<MaterialRef> materials, String mimeType,
                                       boolean containsFinancialMeans) {
    }

    /* default */ record DocumentCategory(CaseDocument caseDocument) {
    }

    /* default */ record CaseDocument(UUID prosecutionCaseId) {
    }

    /* default */ record MaterialRef(UUID id) {
    }
}
